  /**
   * Helper function that returns human-readable default text if a translation key is missing.
   * Converts raw dot-notation keys (e.g., "patient.compareAssessments") into clean, capitalized copy
   * ("Compare Assessments") so that raw keys are never displayed across the dashboard.
   *
   * @param {string} key - The dot-notated translation key.
   * @param {string} [fallback] - Optional custom fallback string.
   * @returns {string} Human-readable default text.
   */
  function getFallbackText(key, fallback = "") {
    if (fallback && typeof fallback === "string" && fallback.trim() !== "" && fallback.trim() !== key) {
      return fallback.trim();
    }
    if (!key || typeof key !== "string") return "";

    const trimmed = key.trim();
    if (!trimmed.includes(".")) {
      const lower = trimmed.toLowerCase();
      if (KNOWN_ACRONYMS[lower]) return KNOWN_ACRONYMS[lower];
      const cleaned = trimmed.replace(/[-_]+/g, " ").trim();
      return cleaned ? cleaned.charAt(0).toUpperCase() + cleaned.slice(1) : "";
    }

    const segments = trimmed.split(".");
    const leaf = segments[segments.length - 1] || trimmed;
    const lowerLeaf = leaf.toLowerCase();

    if (KNOWN_ACRONYMS[lowerLeaf]) {
      return KNOWN_ACRONYMS[lowerLeaf];
    }

    let candidate = leaf;
    const genericLeaves = ["title", "subtitle", "desc", "label", "btn", "text", "heading", "name", "badge", "note", "type"];
    if (genericLeaves.includes(lowerLeaf) && segments.length > 1) {
      const parent = segments[segments.length - 2];
      candidate = `${parent} ${leaf}`;
    }

    const words = candidate
      .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
      .replace(/[-_]+/g, " ")
      .trim()
      .split(/\s+/);

    return words
      .map((w) => {
        const lw = w.toLowerCase();
        if (KNOWN_ACRONYMS[lw]) return KNOWN_ACRONYMS[lw];
        if (["of", "and", "in", "to", "for", "with", "or", "on", "at"].includes(lw) && words[0] !== w) {
          return lw;
        }
        return w.charAt(0).toUpperCase() + w.slice(1);
      })
      .join(" ");
  }

  /**
   * Core I18n Engine Class
   */
  class I18nEngine {
    constructor(options = {}) {
      this.defaultLanguage = options.defaultLanguage || DEFAULT_LANGUAGE;
      this.supportedLanguages = options.supportedLanguages || SUPPORTED_LANGUAGES;
      this.catalog = translations;
      this.listeners = [];

      // Determine initial language: URL query (?lang=) -> stored preference -> device language (navigator.language) -> default
      let initialLang = null;
      try {
        if (typeof window !== "undefined" && window.location && window.location.search) {
          const urlParams = new URLSearchParams(window.location.search);
          const qLang = (urlParams.get("lang") || "").toLowerCase().trim();
          if (this.supportedLanguages.includes(qLang)) {
            initialLang = qLang;
          }
        }
      } catch (e) {}

      if (!initialLang) {
        try {
          if (typeof localStorage !== "undefined") {
            const stored = localStorage.getItem(STORAGE_KEY);
            if (stored && this.supportedLanguages.includes(stored)) {
              initialLang = stored;
            }
          }
        } catch (e) {}
      }

      // Auto-detect from user device language (navigator.language / navigator.languages) if first visit
      if (!initialLang) {
        try {
          const navLang = (typeof navigator !== "undefined" && (navigator.language || (navigator.languages && navigator.languages[0])) || "").toLowerCase().trim();
          if (navLang.startsWith("ar")) {
            initialLang = "ar";
          } else {
            initialLang = "en";
          }
        } catch (e) {
          initialLang = this.defaultLanguage;
        }
      }

      this.currentLanguage = initialLang || this.defaultLanguage;
    }

    getLanguage() {
      return this.currentLanguage;
    }

    getDirection(lang = this.currentLanguage) {
      return lang === "ar" ? "rtl" : "ltr";
    }

    /**
     * Fallback helper function that returns human-readable default text if a key is missing.
     */
    getFallbackText(key, fallback = "") {
      return getFallbackText(key, fallback);
    }

    /**
     * Translates a structured key with optional interpolation params and fallback.
     * Also checks flat legacy mappings for complete backward compatibility.
     */
    t(key, params = null, fallback = "") {
      if (!key) return "";

      const lang = this.currentLanguage;

      // 1. Try structured catalog lookup in current language
      let result = getNestedValue(this.catalog[lang], key);

      // 2. Try structured catalog lookup in fallback language (en or ar)
      if (result === undefined && lang !== this.defaultLanguage) {
        result = getNestedValue(this.catalog[this.defaultLanguage], key);
      }

      // 3. Fallback to legacy window.uiText or window.enToAr if available
      if (result === undefined && typeof window !== "undefined") {
        const trimmed = typeof key === "string" ? key.trim() : key;
        if (lang === "en" && window.uiText && window.uiText[trimmed]) {
          result = window.uiText[trimmed];
        } else if (lang === "ar" && window.enToAr && window.enToAr[trimmed]) {
          result = window.enToAr[trimmed];
        }
      }

      // 4. Fallback value or original key
      if (result === undefined) {
        result = (fallback !== "" && fallback !== undefined) ? fallback : key;
      }

      // 5. Parameter interpolation
      return interpolate(String(result), params);
    }

    /**
     * Formats a date object or ISO string in the active locale.
     */
    formatDate(date, options = { dateStyle: "medium" }) {
      if (!date) return "";
      const d = date instanceof Date ? date : (date.toDate ? date.toDate() : new Date(date));
      if (isNaN(d.getTime())) return String(date);
      const locale = this.currentLanguage === "ar" ? "ar-EG" : "en-US";
      try {
        return new Intl.DateTimeFormat(locale, options).format(d);
      } catch (e) {
        return d.toLocaleDateString();
      }
    }

    /**
     * Formats a time in the active locale.
     */
    formatTime(date, options = { timeStyle: "short" }) {
      if (!date) return "";
      const d = date instanceof Date ? date : (date.toDate ? date.toDate() : new Date(date));
      if (isNaN(d.getTime())) return String(date);
      const locale = this.currentLanguage === "ar" ? "ar-EG" : "en-US";
      try {
        return new Intl.DateTimeFormat(locale, options).format(d);
      } catch (e) {
        return d.toLocaleTimeString();
      }
    }

    /**
     * Formats full date and time in the active locale.
     */
    formatDateTime(date, options = { dateStyle: "medium", timeStyle: "short" }) {
      if (!date) return "";
      const d = date instanceof Date ? date : (date.toDate ? date.toDate() : new Date(date));
      if (isNaN(d.getTime())) return String(date);
      const locale = this.currentLanguage === "ar" ? "ar-EG" : "en-US";
      try {
        return new Intl.DateTimeFormat(locale, options).format(d);
      } catch (e) {
        return `${d.toLocaleDateString()} ${d.toLocaleTimeString()}`;
      }
    }

    /**
     * Formats a number with commas and standard locale-aware numerals.
     */
    formatNumber(num, options = {}) {
      if (num === null || num === undefined || num === "" || isNaN(Number(num))) return String(num ?? "");
      const locale = this.currentLanguage === "ar" ? "ar-EG" : "en-US";
      try {
        return new Intl.NumberFormat(locale, options).format(Number(num));
      } catch (e) {
        return String(num);
      }
    }

    /**
     * Formats a percentage value (e.g., 95 -> "95%" or "%95" / "٩٥٪")
     */
    formatPercent(num) {
      if (num === null || num === undefined || num === "" || isNaN(Number(num))) return String(num ?? "");
      const formatted = this.formatNumber(num);
      return this.currentLanguage === "ar" ? `%${formatted}` : `${formatted}%`;
    }

    /**
     * Sets the active language, updates document attributes, persists to storage,
     * triggers declarative DOM updates, and notifies listeners.
     */
    setLanguage(lang, updateDOM = true) {
      if (!this.supportedLanguages.includes(lang)) {
        console.warn(`[i18n] Language '${lang}' not supported. Using '${this.defaultLanguage}'.`);
        lang = this.defaultLanguage;
      }

      const prevLang = this.currentLanguage;
      this.currentLanguage = lang;

      try {
        if (typeof localStorage !== "undefined") {
          localStorage.setItem(STORAGE_KEY, lang);
        }
      } catch (e) {}

      // Update HTML root and body attributes explicitly to prevent layout inversion and icon overlapping
      const targetDir = this.getDirection(lang);
      if (typeof document !== "undefined") {
        if (document.documentElement) {
          document.documentElement.lang = lang;
          document.documentElement.dir = targetDir;
        }
        if (document.body) {
          document.body.dir = targetDir;
        }
      }

      // Translate DOM declaratively if requested
      if (updateDOM && typeof document !== "undefined") {
        this.translateDOM(document);
      }

      // Dispatch custom DOM event
      if (typeof document !== "undefined" && typeof document.dispatchEvent === "function") {
        try {
          const event = new CustomEvent("hv:languageChanged", {
            detail: {
              language: lang,
              direction: this.getDirection(lang),
              previousLanguage: prevLang
            }
          });
          document.dispatchEvent(event);
        } catch (e) {}
      }

      // Notify registered subscribers
      this.listeners.forEach((fn) => {
        try {
          fn(lang, prevLang);
        } catch (err) {
          console.error("[i18n] Listener error:", err);
        }
      });

      return lang;
    }

    /**
     * Subscribe to language change events.
     */
    onLanguageChange(callback) {
      if (typeof callback === "function") {
        this.listeners.push(callback);
      }
      return () => {
        this.listeners = this.listeners.filter((fn) => fn !== callback);
      };
    }

    /**
     * Register additional translations dynamically into a namespace.
     */
    registerTranslations(lang, namespace, strings) {
      if (!this.catalog[lang]) {
        this.catalog[lang] = {};
      }
      if (namespace) {
        this.catalog[lang][namespace] = {
          ...(this.catalog[lang][namespace] || {}),
          ...strings
        };
      } else {
        this.catalog[lang] = {
          ...this.catalog[lang],
          ...strings
        };
      }
    }

    /**
     * Declarative DOM Translator:
     * Fast, targeted scan of elements bearing data-i18n attributes.
     * Strictly preserves user-typed input field values.
     */
    translateDOM(root = document) {
      if (!root || typeof root.querySelectorAll !== "function") return;

      const parseParams = (el) => {
        const raw = el.getAttribute("data-i18n-params");
        if (!raw) return null;
        try {
          return JSON.parse(raw);
        } catch (e) {
          return null;
        }
      };

      const isRawKey = (str) => {
        if (!str || typeof str !== "string") return false;
        return /^[a-zA-Z0-9_-]+(\.[a-zA-Z0-9_-]+)+$/.test(str.trim());
      };

      // 1. Text content
      const textEls = root.querySelectorAll("[data-i18n]");
      for (let i = 0; i < textEls.length; i++) {
        const el = textEls[i];
        const key = el.getAttribute("data-i18n");
        if (key) {
          const params = parseParams(el);
          const currentText = el.textContent ? el.textContent.trim() : "";
          const hasHumanText = Boolean(currentText && currentText !== key && !isRawKey(currentText));
          const fallback = hasHumanText ? currentText : this.getFallbackText(key);
          el.textContent = this.t(key, params, fallback);
        }
      }

      // 2. Safe HTML markup
      const htmlEls = root.querySelectorAll("[data-i18n-html]");
      for (let i = 0; i < htmlEls.length; i++) {
        const el = htmlEls[i];
        const key = el.getAttribute("data-i18n-html");
        if (key) {
          const params = parseParams(el);
          const currentHtml = el.innerHTML ? el.innerHTML.trim() : "";
          const hasHumanHtml = Boolean(currentHtml && currentHtml !== key && !isRawKey(currentHtml));
          const fallback = hasHumanHtml ? currentHtml : this.getFallbackText(key);
          el.innerHTML = this.t(key, params, fallback);
        }
      }

      // 3. Placeholders (Preserves input value!)
      const placeholderEls = root.querySelectorAll("[data-i18n-placeholder]");
      for (let i = 0; i < placeholderEls.length; i++) {
        const el = placeholderEls[i];
        const key = el.getAttribute("data-i18n-placeholder");
        if (key) {
          const params = parseParams(el);
          const currentPlaceholder = el.placeholder ? el.placeholder.trim() : "";
          const hasHumanPlaceholder = Boolean(currentPlaceholder && currentPlaceholder !== key && !isRawKey(currentPlaceholder));
          const fallback = hasHumanPlaceholder ? currentPlaceholder : this.getFallbackText(key);
          el.placeholder = this.t(key, params, fallback);
        }
      }

      // 4. Tooltip / Titles
      const titleEls = root.querySelectorAll("[data-i18n-title]");
      for (let i = 0; i < titleEls.length; i++) {
        const el = titleEls[i];
        const key = el.getAttribute("data-i18n-title");
        if (key) {
          const params = parseParams(el);
          const currentTitle = el.title ? el.title.trim() : "";
          const hasHumanTitle = Boolean(currentTitle && currentTitle !== key && !isRawKey(currentTitle));
          const fallback = hasHumanTitle ? currentTitle : this.getFallbackText(key);
          el.title = this.t(key, params, fallback);
        }
      }

      // 5. Accessibility Aria Labels
      const ariaEls = root.querySelectorAll("[data-i18n-aria]");
      for (let i = 0; i < ariaEls.length; i++) {
        const el = ariaEls[i];
        const key = el.getAttribute("data-i18n-aria");
        if (key) {
          const params = parseParams(el);
          const currentAria = el.getAttribute("aria-label") ? el.getAttribute("aria-label").trim() : "";
          const hasHumanAria = Boolean(currentAria && currentAria !== key && !isRawKey(currentAria));
          const fallback = hasHumanAria ? currentAria : this.getFallbackText(key);
          el.setAttribute("aria-label", this.t(key, params, fallback));
        }
      }

      // 6. Values (explicitly tagged with [data-i18n-value])
      const valueEls = root.querySelectorAll("[data-i18n-value]");
      for (let i = 0; i < valueEls.length; i++) {
        const el = valueEls[i];
        const key = el.getAttribute("data-i18n-value");
        if (key) {
          const params = parseParams(el);
          const currentValue = el.value ? el.value.trim() : "";
          const hasHumanValue = Boolean(currentValue && currentValue !== key && !isRawKey(currentValue));
          const fallback = hasHumanValue ? currentValue : this.getFallbackText(key);
          el.value = this.t(key, params, fallback);
        }
      }
    }

    /**
     * Wrap numeric/stat figures in <bdi> to preserve natural LTR reading order in RTL mode
     */
    isolateBidi(text) {
      return isolateBidi(text);
    }

    /**
     * Format percentage with LTR bidi isolation
     */
    formatBidiPercent(num) {
      return formatBidiPercent(num);
    }
  }

  /**
   * Helper to wrap bidirectional text, stats, percentages, and comparison operators in <bdi>
   * with CSS isolation so they read naturally without reverse inversion in Arabic RTL mode.
   */
  function isolateBidi(text) {
    if (text === null || text === undefined || text === "") return "";
    return `<bdi class="bidi-isolate">${text}</bdi>`;
  }

  function formatBidiPercent(num) {
    if (num === null || num === undefined || num === "") return "";
    return `<bdi class="bidi-isolate">${num}%</bdi>`;
  }

